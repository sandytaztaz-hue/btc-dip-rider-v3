interface DipTranche {
  entry: bigint; // close the tranche was bought at
  qty: bigint; // estimated filled qty (sell side always caps at held qty)
  bar: number; // decision bar of the entry
}

function minBig(a: bigint, b: bigint, c: bigint): bigint {
  let m = a < b ? a : b;
  if (c < m) m = c;
  return m;
}

