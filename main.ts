let peakEquity = 0n;
let minNotional = MICRO_PER_USD;
let feeBps = 4n;
let halted = false;
let scheduledPosition = 0n; // scheduled (not clipped) net long, micro-USDC
let lastScheduleBar = -1_000_000;
const closes: bigint[] = []; // every CBBTC close seen, in arrival order
const tranches: DipTranche[] = []; // open dip-buyer tranches, oldest first

function decide(state: BarsState, batch: Batch): OrderInput[] {
  const seq = state.seq;
  const close = state.close(SYMBOL);
  if (close === null) return [];
  closes.push(close);

  // Safety: 25% equity-drawdown halt. Flatten once, then stay out.
  if (state.equity > peakEquity) peakEquity = state.equity;
  if (!halted && state.equity * BPS <= peakEquity * (BPS - HALT_BPS)) {
    halted = true;
    const held = state.positions.get(SYMBOL)?.qty ?? 0n;
    if (held > 0n) {
      return [{ side: 'sell', symbol: SYMBOL, qty: held, max_slippage_bps: SLIPPAGE_BPS }];
    }
    return [];
  }
  if (halted || state.warmingUp) return [];

  const heldQty = state.positions.get(SYMBOL)?.qty ?? 0n;
  // Position value at THIS batch's close, frozen for the whole reply:
  // fills decided here have not happened yet.
  const posValue = state.value(SYMBOL, heldQty, close);
  let cashLeft = state.cash;
  const orders: OrderInput[] = [];

  // ---- Mode 1: the compounded DP tranche schedule -------------------
  const actions = PLAN.get(seq);
  if (actions !== undefined) {
    let roomLeft = state.weightRoom(SYMBOL);
    for (const action of actions) {
      // Gate: fire only if the live close is within 60 bps of the dev close.
      const ref = action.ref;
      const diff = close >= ref ? close - ref : ref - close;
      if (diff * BPS > ref * GATE_BPS) continue;
      if (action.buy) {
        const amt = minBig(action.size, cashLeft, roomLeft);
        if (amt < minNotional) continue;
        orders.push({ side: 'buy', symbol: SYMBOL, notional_quote_units: amt, max_slippage_bps: SLIPPAGE_BPS });
        cashLeft -= amt;
        roomLeft -= amt;
        scheduledPosition += action.size;
      } else {
        if (heldQty <= 0n || posValue <= 0n) continue;
        let q = (heldQty * action.size) / posValue;
        if (q > heldQty) q = heldQty;
        if (q <= 0n) continue;
        orders.push({ side: 'sell', symbol: SYMBOL, qty: q, max_slippage_bps: SLIPPAGE_BPS });
        scheduledPosition -= action.size;
      }
    }
    if (orders.length > 0) {
      lastScheduleBar = seq;
      return orders;
    }
  }

  // ---- Mode 2: dip-buyer fallback (only off-schedule) ---------------
  const quietLongEnough = seq - lastScheduleBar >= DORMANCY_BARS;
  if (scheduledPosition <= ONE_DOLLAR && quietLongEnough) {
    // Exits first, oldest first: +20 bps or 120 bars old.
    let exitQty = 0n;
    for (let i = tranches.length - 1; i >= 0; i--) {
      const t = tranches[i]!;
      const ripe = close * BPS >= t.entry * (BPS + DIP_EXIT_BPS);
      const stale = seq - t.bar >= DIP_MAX_AGE;
      if (ripe || stale) {
        exitQty += t.qty;
        tranches.splice(i, 1);
      }
    }
    if (exitQty > 0n && heldQty > 0n) {
      if (exitQty > heldQty) exitQty = heldQty;
      orders.push({ side: 'sell', symbol: SYMBOL, qty: exitQty, max_slippage_bps: SLIPPAGE_BPS });
    }
    // Entry: sharp 15-bar dip, but not a 60-bar slide. At most 2 tranches.
    if (closes.length > 60 && tranches.length < DIP_MAX_TRANCHES) {
      const close15 = closes[closes.length - 1 - 15]!;
      const close60 = closes[closes.length - 1 - 60]!;
      const ret15 = ((close - close15) * BPS) / close15;
      const ret60 = ((close - close60) * BPS) / close60;
      if (ret15 <= -40n && ret60 > -100n) {
        const room = 1_000_000_000n - posValue; // $1,000 cap minus position value
        const amt = minBig(DIP_SIZE, cashLeft, room > 0n ? room : 0n);
        if (amt >= minNotional) {
          orders.push({ side: 'buy', symbol: SYMBOL, notional_quote_units: amt, max_slippage_bps: SLIPPAGE_BPS });
          // Estimated filled qty: notional after the 4 bps fee, at this close.
          const sym = state.symbols.get(SYMBOL)!;
          const net = (amt * (BPS - feeBps)) / BPS;
          const qtyEst = (net * 10n ** BigInt(sym.qty_scale + sym.price_scale)) /
            (close * 10n ** BigInt(state.hello.capital.quote_scale));
          tranches.push({ entry: close, qty: qtyEst, bar: seq });
        }
      }
    }
  }
  return orders;
}

